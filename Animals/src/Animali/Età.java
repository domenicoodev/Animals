package Animali;

public class Età {
    private int anniSpecie;
    private int mesiSpecie;

    public Età(int anni, int mesi) {
        this.anniSpecie = anni;
        this.mesiSpecie = mesi;
    }

    public int getAnniSpecie(){return anniSpecie;}
    public int getMesiSpecie(){return mesiSpecie;}
}
